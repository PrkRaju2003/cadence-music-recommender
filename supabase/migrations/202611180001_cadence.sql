-- Dedicated application schema. No database password or service-role key is
-- exposed to the app. All authenticated RPCs derive identity from auth.uid().
CREATE SCHEMA IF NOT EXISTS cadence;
REVOKE ALL ON SCHEMA cadence FROM PUBLIC, anon, authenticated;

CREATE TABLE cadence.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL CHECK (length(btrim(display_name)) BETWEEN 1 AND 80),
  email text NOT NULL UNIQUE CHECK (position('@' in email)>1),
  created_at timestamptz NOT NULL DEFAULT now(),
  is_demo boolean NOT NULL DEFAULT false,
  CHECK ((is_demo AND auth_id IS NULL) OR (NOT is_demo AND auth_id IS NOT NULL))
);
CREATE TABLE cadence.artists (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE cadence.genres (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE cadence.albums (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artist_id bigint NOT NULL REFERENCES cadence.artists(id), title text NOT NULL,
  release_year integer NOT NULL CHECK(release_year BETWEEN 1900 AND 2100),
  color text NOT NULL CHECK(color ~ '^#[0-9a-fA-F]{6}$'), UNIQUE(artist_id,title)
);
CREATE TABLE cadence.tracks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  album_id bigint NOT NULL REFERENCES cadence.albums(id), genre_id bigint NOT NULL REFERENCES cadence.genres(id),
  title text NOT NULL, track_number integer NOT NULL CHECK(track_number>0),
  duration_ms integer NOT NULL CHECK(duration_ms BETWEEN 1000 AND 3600000), UNIQUE(album_id,track_number)
);
CREATE TABLE cadence.user_genres (
  user_id bigint REFERENCES cadence.users(id) ON DELETE CASCADE,
  genre_id bigint REFERENCES cadence.genres(id), PRIMARY KEY(user_id,genre_id)
);
CREATE TABLE cadence.listening_sessions (
  id text PRIMARY KEY, user_id bigint NOT NULL REFERENCES cadence.users(id) ON DELETE CASCADE,
  started_at timestamptz NOT NULL DEFAULT now(), ended_at timestamptz,
  CHECK(ended_at IS NULL OR ended_at>=started_at)
);
CREATE TABLE cadence.playback_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id text NOT NULL REFERENCES cadence.listening_sessions(id) ON DELETE CASCADE,
  track_id bigint NOT NULL REFERENCES cadence.tracks(id), played_at timestamptz NOT NULL DEFAULT now(),
  played_ms integer NOT NULL CHECK(played_ms>=0),
  source text NOT NULL CHECK(source IN ('catalog','recommendation','seed')),
  event_key text NOT NULL UNIQUE CHECK(length(event_key) BETWEEN 1 AND 100)
);
CREATE FUNCTION cadence.playback_bounds() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, cadence AS $$
DECLARE s cadence.listening_sessions; d integer;
BEGIN
  SELECT * INTO s FROM cadence.listening_sessions WHERE id=NEW.session_id;
  SELECT duration_ms INTO d FROM cadence.tracks WHERE id=NEW.track_id;
  IF NEW.played_ms>d OR NEW.played_at<s.started_at OR s.ended_at IS NOT NULL THEN
    RAISE EXCEPTION 'Invalid playback bounds or closed session' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER playback_bounds BEFORE INSERT OR UPDATE ON cadence.playback_events
FOR EACH ROW EXECUTE FUNCTION cadence.playback_bounds();
CREATE TABLE cadence.likes (
  user_id bigint REFERENCES cadence.users(id) ON DELETE CASCADE,
  track_id bigint REFERENCES cadence.tracks(id), created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(user_id,track_id)
);
CREATE TABLE cadence.recommendation_requests (
  id text PRIMARY KEY, user_id bigint NOT NULL REFERENCES cadence.users(id) ON DELETE CASCADE,
  requested_at timestamptz NOT NULL DEFAULT now(), model_version text NOT NULL,
  strategy text NOT NULL CHECK(strategy IN ('hybrid','sequence','collaborative','popularity')),
  latency_ms numeric(12,3) NOT NULL CHECK(latency_ms>=0)
);
CREATE TABLE cadence.recommendation_items (
  request_id text REFERENCES cadence.recommendation_requests(id) ON DELETE CASCADE,
  track_id bigint REFERENCES cadence.tracks(id), rank integer NOT NULL CHECK(rank>0),
  score numeric NOT NULL CHECK(score BETWEEN 0 AND 1.000001),
  PRIMARY KEY(request_id,track_id), UNIQUE(request_id,rank)
);
CREATE INDEX idx_sessions_user_time ON cadence.listening_sessions(user_id,started_at DESC);
CREATE INDEX idx_playback_session_time ON cadence.playback_events(session_id,played_at,id);
CREATE INDEX idx_playback_track_time ON cadence.playback_events(track_id,played_at);
CREATE INDEX idx_playback_time ON cadence.playback_events(played_at);
CREATE INDEX idx_tracks_genre ON cadence.tracks(genre_id,id);
CREATE INDEX idx_tracks_album ON cadence.tracks(album_id,track_number);
CREATE INDEX idx_requests_user_time ON cadence.recommendation_requests(user_id,requested_at DESC);

CREATE VIEW cadence.track_catalog WITH (security_invoker=true) AS
SELECT t.id,t.title,t.track_number,t.duration_ms,t.album_id,a.title AS album,a.color,a.release_year,
       ar.name AS artist,g.id AS genre_id,g.name AS genre
FROM cadence.tracks t JOIN cadence.albums a ON a.id=t.album_id
JOIN cadence.artists ar ON ar.id=a.artist_id JOIN cadence.genres g ON g.id=t.genre_id;
CREATE VIEW cadence.playback_fact WITH (security_invoker=true) AS
SELECT e.id AS event_id,s.user_id,e.session_id,e.track_id,e.played_at,
       to_char(e.played_at AT TIME ZONE 'UTC','YYYY-MM-DD') AS play_date,
       e.played_ms,t.duration_ms,round(1.0*e.played_ms/t.duration_ms,4) AS completion,
       CASE WHEN 1.0*e.played_ms/t.duration_ms<0.3 THEN 1 ELSE 0 END AS skipped,e.source
FROM cadence.playback_events e JOIN cadence.listening_sessions s ON s.id=e.session_id
JOIN cadence.tracks t ON t.id=e.track_id;

CREATE FUNCTION cadence.current_user_id() RETURNS bigint LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE result bigint;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Authentication required' USING ERRCODE='42501'; END IF;
  SELECT id INTO result FROM cadence.users WHERE auth_id=auth.uid() AND NOT is_demo;
  IF result IS NULL THEN RAISE EXCEPTION 'Profile not found' USING ERRCODE='42501'; END IF;
  RETURN result;
END $$;

CREATE FUNCTION cadence.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE new_id bigint; genre integer;
BEGIN
  INSERT INTO cadence.users(auth_id,display_name,email)
  VALUES(NEW.id,left(coalesce(nullif(btrim(NEW.raw_user_meta_data->>'display_name'),''),'Music lover'),80),NEW.email)
  RETURNING id INTO new_id;
  IF coalesce(NEW.raw_user_meta_data->>'genre_id','') ~ '^[1-4]$' THEN
    genre := (NEW.raw_user_meta_data->>'genre_id')::integer;
    INSERT INTO cadence.user_genres VALUES(new_id,genre) ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER on_cadence_user_created AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION cadence.handle_new_user();

-- RLS is enabled on every application table. No direct table access is granted;
-- explicit policies retain owner isolation if read access is granted later.
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['users','artists','genres','albums','tracks','user_genres','listening_sessions','playback_events','likes','recommendation_requests','recommendation_items'] LOOP
    EXECUTE format('ALTER TABLE cadence.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON cadence.%I FROM PUBLIC,anon,authenticated',t);
  END LOOP;
END $$;
CREATE POLICY own_profile ON cadence.users FOR SELECT TO authenticated USING(auth_id=auth.uid());
CREATE POLICY own_sessions ON cadence.listening_sessions FOR SELECT TO authenticated
USING(user_id=(SELECT cadence.current_user_id()));
CREATE POLICY own_plays ON cadence.playback_events FOR SELECT TO authenticated
USING(session_id IN (SELECT id FROM cadence.listening_sessions WHERE user_id=(SELECT cadence.current_user_id())));

CREATE FUNCTION public.cadence_catalog() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$ SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY t.id),'[]') FROM cadence.track_catalog t $$;
CREATE FUNCTION public.cadence_genres() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$ SELECT coalesce(jsonb_agg(to_jsonb(g) ORDER BY g.id),'[]') FROM cadence.genres g $$;
CREATE FUNCTION public.cadence_health() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$ SELECT jsonb_build_object('status','ok','database','supabase-postgresql') $$;
CREATE FUNCTION public.cadence_profile() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
SELECT jsonb_build_object('id',u.id,'display_name',u.display_name,'genre_ids',
       coalesce((SELECT jsonb_agg(genre_id) FROM cadence.user_genres WHERE user_id=u.id),'[]'))
FROM cadence.users u WHERE u.id=cadence.current_user_id() $$;
CREATE FUNCTION public.cadence_start_session() RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE result text:=gen_random_uuid()::text; uid bigint:=cadence.current_user_id();
BEGIN
  INSERT INTO cadence.listening_sessions(id,user_id) VALUES(result,uid);
  RETURN jsonb_build_object('id',result,'user_id',uid);
END $$;

CREATE FUNCTION public.cadence_record_play(p_session_id text,p_track_id bigint,p_played_ms integer,p_source text,p_event_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,cadence AS $$
DECLARE uid bigint:=cadence.current_user_id(); existing cadence.playback_events; result bigint;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM cadence.listening_sessions WHERE id=p_session_id AND user_id=uid) THEN
    RAISE EXCEPTION 'Session not found' USING ERRCODE='42501';
  END IF;
  IF p_source NOT IN ('catalog','recommendation') THEN RAISE EXCEPTION 'Invalid source' USING ERRCODE='22023'; END IF;
  INSERT INTO cadence.playback_events(session_id,track_id,played_ms,source,event_key)
  VALUES(p_session_id,p_track_id,p_played_ms,p_source,p_event_key) ON CONFLICT(event_key) DO NOTHING RETURNING id INTO result;
  IF result IS NOT NULL THEN RETURN jsonb_build_object('id',result,'duplicate',false); END IF;
  SELECT * INTO existing FROM cadence.playback_events WHERE event_key=p_event_key;
  IF existing.session_id<>p_session_id OR existing.track_id<>p_track_id OR existing.played_ms<>p_played_ms OR existing.source<>p_source THEN
    RAISE EXCEPTION 'Event key already used' USING ERRCODE='23505';
  END IF;
  RETURN jsonb_build_object('id',existing.id,'duplicate',true);
END $$;

CREATE FUNCTION public.cadence_history(p_limit integer DEFAULT 20) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE uid bigint:=cadence.current_user_id(); result jsonb;
BEGIN
  IF p_limit NOT BETWEEN 1 AND 100 THEN RAISE EXCEPTION 'Invalid limit' USING ERRCODE='22023'; END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(h) ORDER BY h.played_at DESC,h.id DESC),'[]') INTO result FROM
  (SELECT e.id,e.played_at,e.played_ms,c.title,c.artist,c.album FROM cadence.playback_events e
   JOIN cadence.listening_sessions s ON s.id=e.session_id JOIN cadence.track_catalog c ON c.id=e.track_id
   WHERE s.user_id=uid ORDER BY e.played_at DESC,e.id DESC LIMIT p_limit) h;
  RETURN result;
END $$;

-- Model fitting can see synthetic seed interactions and only the caller's real
-- history. It cannot reveal another signed-in user's private playback.
CREATE FUNCTION public.cadence_training_events() RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
SELECT coalesce(jsonb_agg(to_jsonb(x) ORDER BY x.played_at,x.id),'[]') FROM
(SELECT e.id,e.session_id,s.user_id,e.track_id,e.played_at,1.0*e.played_ms/t.duration_ms AS completion
 FROM cadence.playback_events e JOIN cadence.listening_sessions s ON s.id=e.session_id
 JOIN cadence.users u ON u.id=s.user_id JOIN cadence.tracks t ON t.id=e.track_id
 WHERE u.is_demo OR u.id=cadence.current_user_id()) x $$;

CREATE FUNCTION public.cadence_like(p_track_id bigint) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$ BEGIN
  INSERT INTO cadence.likes(user_id,track_id) VALUES(cadence.current_user_id(),p_track_id) ON CONFLICT DO NOTHING;
  RETURN jsonb_build_object('liked',true);
END $$;
CREATE FUNCTION public.cadence_log_recommendations(p_id text,p_model text,p_strategy text,p_latency numeric,p_items jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,cadence AS $$
DECLARE uid bigint:=cadence.current_user_id(); item jsonb;
BEGIN
  IF jsonb_typeof(p_items)<>'array' OR jsonb_array_length(p_items)>24 OR length(p_id)>80 OR length(p_model)>80 THEN
    RAISE EXCEPTION 'Invalid recommendation request' USING ERRCODE='22023';
  END IF;
  INSERT INTO cadence.recommendation_requests(id,user_id,model_version,strategy,latency_ms)
  VALUES(p_id,uid,p_model,p_strategy,p_latency);
  FOR item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    INSERT INTO cadence.recommendation_items VALUES(p_id,(item->>'track_id')::bigint,(item->>'rank')::integer,(item->>'score')::numeric);
  END LOOP;
  RETURN jsonb_build_object('saved',true);
END $$;
CREATE FUNCTION public.cadence_analytics() RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE uid bigint:=cadence.current_user_id(); totals jsonb; daily jsonb; genres jsonb; model jsonb;
BEGIN
  SELECT jsonb_build_object('plays',count(*),'listeners',count(DISTINCT user_id),'sessions',count(DISTINCT session_id),
    'listening_minutes',coalesce(round(sum(played_ms)/60000.0,2),0),'completion_pct',coalesce(round(avg(completion)*100,1),0),
    'skip_pct',coalesce(round(avg(skipped)*100,1),0)) INTO totals FROM cadence.playback_fact WHERE user_id=uid;
  SELECT coalesce(jsonb_agg(to_jsonb(d) ORDER BY d.play_date),'[]') INTO daily FROM
    (SELECT play_date,count(*) AS plays,count(DISTINCT user_id) AS active_users FROM cadence.playback_fact WHERE user_id=uid GROUP BY play_date) d;
  SELECT coalesce(jsonb_agg(to_jsonb(g) ORDER BY g.plays DESC),'[]') INTO genres FROM
    (SELECT c.genre,count(*) AS plays FROM cadence.playback_fact f JOIN cadence.track_catalog c ON c.id=f.track_id
     WHERE f.user_id=uid GROUP BY c.genre) g;
  SELECT jsonb_build_object('requests',count(*),'avg_latency_ms',coalesce(round(avg(latency_ms),2),0)) INTO model
    FROM cadence.recommendation_requests WHERE user_id=uid;
  RETURN jsonb_build_object('totals',totals,'daily',daily,'genres',genres,'model',model,'data_note','Your private Supabase listening activity.');
END $$;

CREATE FUNCTION public.cadence_sql_report(p_report text,p_limit integer DEFAULT 20) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path=pg_catalog,cadence AS $$
DECLARE uid bigint:=cadence.current_user_id(); result jsonb;
BEGIN
  IF p_limit NOT BETWEEN 1 AND 50 THEN RAISE EXCEPTION 'Invalid limit' USING ERRCODE='22023'; END IF;
  IF p_report='top_tracks' THEN
    SELECT coalesce(jsonb_agg(to_jsonb(x)),'[]') INTO result FROM
    (SELECT c.title,c.artist,count(*) AS plays,round(avg(f.completion)*100,1) AS completion_pct
     FROM cadence.playback_fact f JOIN cadence.track_catalog c ON c.id=f.track_id WHERE f.user_id=uid
     GROUP BY c.id,c.title,c.artist ORDER BY plays DESC,c.title LIMIT p_limit) x;
  ELSIF p_report='daily_activity' THEN
    SELECT coalesce(jsonb_agg(to_jsonb(x)),'[]') INTO result FROM
    (SELECT play_date,count(*) AS plays,round(sum(played_ms)/60000.0,2) AS minutes
     FROM cadence.playback_fact WHERE user_id=uid GROUP BY play_date ORDER BY play_date DESC LIMIT p_limit) x;
  ELSIF p_report='catalog_summary' THEN
    SELECT coalesce(jsonb_agg(to_jsonb(x)),'[]') INTO result FROM
    (SELECT genre,count(*) AS tracks,count(DISTINCT album_id) AS albums FROM cadence.track_catalog GROUP BY genre ORDER BY genre LIMIT p_limit) x;
  ELSE RAISE EXCEPTION 'Unknown report' USING ERRCODE='22023'; END IF;
  RETURN result;
END $$;

-- Explicit function grants prevent arbitrary writes or impersonation through
-- PostgREST. Only public catalog/health endpoints are callable anonymously.
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA cadence FROM PUBLIC,anon,authenticated;
DO $$ DECLARE f record; BEGIN
  FOR f IN SELECT p.oid::regprocedure AS signature,p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname LIKE 'cadence\_%' ESCAPE '\' LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,anon,authenticated',f.signature);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO authenticated',f.signature);
    IF f.proname IN ('cadence_catalog','cadence_genres','cadence_health') THEN
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO anon',f.signature);
    END IF;
  END LOOP;
END $$;
NOTIFY pgrst, 'reload schema';
